/** Searches both display languages without translating or changing stable slugs. */
export function matchesMarketingSkill(skill: {
  slug: string;
  title: string;
  summary: string;
  categoryTitle: string;
  highlightLabel: string | null;
  reason: string | null;
  guides: { label: string }[];
}, query: string): boolean {
  const needle = query.trim().toLowerCase();
  if (!needle) return true;
  const categoryIds: Record<string, string> = {
    "SEO and content": "seo", "Conversion": "cro", "Content and copy": "copy",
    "Paid and measurement": "paid", "Growth and retention": "growth",
    "Sales and go-to-market": "gtm", "Strategy": "strategy", "Other": "other",
  };
  return [
    skill.title, skill.slug, skill.summary, skill.categoryTitle,
    skill.highlightLabel, skill.reason,
    ...(skillChinese[skill.slug] ?? []), reasonChinese[skill.slug],
    ...(categoryChinese[categoryIds[skill.categoryTitle]] ?? []),
    ...skill.guides.flatMap((guide) => [guide.label, guideChinese[guide.label]]),
  ].filter(Boolean).join(" ").toLowerCase().includes(needle);
}
